#!/usr/bin/env python3
"""Generate the chat portrait decorator that the auth proxy injects.

Fasa 7.5 of the plan: images in the chat without rebuilding the harness and without enabling the
host plugin. The proxy already injects four files into every HTML document, and it serves them from
disk on each request, so one generated file plus one line in the proxy's inject list is the whole
change.

The file this writes is self-contained on purpose: it carries its own portrait table, so the
browser needs no second request and no new server route. The table is derived from the manifest.

    python3 scripts/portrait_chat_js.py            # writes the decorator
    python3 scripts/portrait_chat_js.py --check     # reports whether it is current

The resolution rules are the resolver's, restated in the browser's language: the `(id NNN)` tag
first, then whole-word keys longest-first, one image per character, capped per turn, and a name that
matches more than one row attaches nothing.
"""
from __future__ import annotations

import argparse
import json
import pathlib

VAULT = pathlib.Path(__file__).resolve().parents[2]
MANIFEST = VAULT / "adventures/tkg-arc1-restart/prototype/faces/manifest.json"
OUT = pathlib.Path.home() / ".config/dsh-auth/portrait-chat.js"
PATH_PREFIX = "adventures/tkg/characters/"
NEUTRAL = "neutral"


def build_table() -> list[dict]:
    """One entry per character that has a ready neutral portrait.

    @returns rows of {n: name, k: keys, p: path relative to the characters root}, sorted by name so
        the generated file is stable.
    """
    payload = json.loads(MANIFEST.read_text(encoding="utf-8"))
    rows = payload["rows"] if isinstance(payload, dict) else payload
    table: dict[int, dict] = {}
    for row in rows:
        if row.get("kind") != "emotion" or row.get("key") != NEUTRAL:
            continue
        if row.get("status") != "ready" or not row.get("path"):
            continue
        path = str(row["path"])
        if not path.startswith(PATH_PREFIX):
            continue
        table[int(row["id"])] = {
            "id": int(row["id"]),
            "n": str(row["name"]),
            "k": [str(key) for key in (row.get("keys") or [row["name"]])],
            "p": path[len(PATH_PREFIX):],
        }
    return [table[cid] for cid in sorted(table)]


TEMPLATE = """/**
 * portrait-chat.js — a portrait strip under a chat turn, drawn from the prose already on screen.
 *
 * Generated by rp-engine-py/scripts/portrait_chat_js.py from the face manifest. Do not edit by
 * hand: regenerate it. It carries its own table, so it makes no request of its own.
 *
 * The rules match the resolver package (~/projects/dsh-portrait-attach):
 *   - the `(id NNN)` tag wins, because it is exact;
 *   - otherwise whole-word keys, longest first, so a full name beats a short form;
 *   - one portrait per character per turn, capped;
 *   - a key that matches more than one row shows nothing, because guessing a face is worse than
 *     showing none.
 */
(function () {
  'use strict'

  var TABLE = %(table)s
  var CAP = %(cap)d
  var IMAGES = '/tkg-api/characters/'

  function keyPattern(key) {
    // Whole word: bounded by anything that is not a letter, a digit or a hyphen.
    return new RegExp('(?<![\\\\p{L}\\\\p{N}-])' + key.replace(/[.*+?^${}()|[\\]\\\\]/g, '\\\\$&') +
      '(?![\\\\p{L}\\\\p{N}-])', 'giu')
  }

  var KEYS = TABLE.map(function (entry) {
    return { id: entry.id, name: entry.n, keys: entry.k, path: entry.p }
  })

  /** Every key, longest first, with the rows it belongs to. */
  var BY_KEY = (function () {
    var index = {}
    KEYS.forEach(function (entry) {
      entry.keys.forEach(function (key) {
        var bucket = index[key.toLowerCase()] || { key: key, rows: [] }
        bucket.rows.push(entry)
        index[key.toLowerCase()] = bucket
      })
    })
    return Object.keys(index).map(function (lower) { return index[lower] })
      .sort(function (a, b) { return b.key.length - a.key.length })
  })()

  /**
   * The portraits one turn earns.
   *
   * @param text - the turn's prose.
   * @returns an array of {name, path}, in first-mention order, capped.
   */
  function pick(text) {
    if (typeof text !== 'string' || text === '') return []
    var picked = []
    var seen = {}
    // 1. the id pass: exact, and it claims the character outright.
    var idPattern = /\\(id (\\d+)\\)/g
    var match
    while ((match = idPattern.exec(text)) !== null) {
      var id = Number(match[1])
      var entry = null
      for (var i = 0; i < KEYS.length; i += 1) { if (KEYS[i].id === id) { entry = KEYS[i]; break } }
      if (entry === null) continue
      if (seen[entry.name]) continue
      seen[entry.name] = true
      picked.push(entry)
    }
    // 2. the key pass.
    for (var k = 0; k < BY_KEY.length && picked.length < CAP; k += 1) {
      var bucket = BY_KEY[k]
      var candidates = bucket.rows.filter(function (row) { return !seen[row.name] })
      if (candidates.length === 0) continue
      if (bucket.rows.length > 1 && new Set(bucket.rows.map(function (r) { return r.name })).size > 1) {
        continue  // ambiguity: refuse rather than guess
      }
      if (!keyPattern(bucket.key).test(text)) continue
      seen[candidates[0].name] = true
      picked.push(candidates[0])
      if (picked.length >= CAP) break
    }
    return picked.slice(0, CAP).map(function (entry) {
      return { name: entry.name, path: entry.path }
    })
  }

  if (typeof module !== 'undefined' && module.exports) { module.exports = { pick: pick, table: KEYS } }

  if (typeof document === 'undefined') return

  /** Attach the strip above a turn's prose, once. */
  function decorate(node) {
    if (node.dataset.portraitDone === '1') return
    var text = node.innerText || node.textContent || ''
    var found = pick(text)
    node.dataset.portraitDone = '1'
    if (found.length === 0) return
    var strip = document.createElement('div')
    strip.className = 'dsh-portrait-strip'
    strip.style.cssText = 'display:flex;gap:8px;margin:6px 0;flex-wrap:wrap'
    found.forEach(function (entry) {
      var img = document.createElement('img')
      img.src = IMAGES + entry.path
      img.alt = entry.name
      img.title = entry.name
      img.loading = 'lazy'
      img.style.cssText = 'width:96px;height:96px;object-fit:cover;border-radius:8px;opacity:.95'
      strip.appendChild(img)
    })
    node.insertBefore(strip, node.firstChild)
  }

  function scan() {
    document.querySelectorAll('[data-message-role="assistant"], .dsh-message-assistant, article')
      .forEach(decorate)
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', scan)
  } else {
    scan()
  }
  new MutationObserver(scan).observe(document.body, { childList: true, subtree: true })
})()
"""


def render() -> str:
    table = build_table()
    compact = json.dumps([{"id": row["id"], "n": row["n"], "k": row["k"], "p": row["p"]}
                          for row in table], ensure_ascii=False, separators=(",", ":"))
    return TEMPLATE % {"table": compact, "cap": 2}


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    body = render()
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.is_file() else ""
        same = current == body
        print(f"portrait-chat.js {'is current' if same else 'is stale'} "
              f"({len(build_table())} characters, {len(body)} bytes)")
        return 0 if same else 1
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(body, encoding="utf-8")
    print(f"wrote {OUT} ({len(build_table())} characters, {len(body)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
